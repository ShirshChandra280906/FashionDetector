"""Collect every measured result into results/RESULTS.md and summary charts.

Only reads files produced by the evaluation scripts, so every number in the
report traces back to a CSV/JSON in results/.

    python -m src.eval.report
"""
from __future__ import annotations

import json

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.config import GROUPS, RESULTS
from src.retrieve import recall_at_k
from src.viz import NEUTRAL, SERIES, style

MODEL_LABEL = {"color_hist": "Colour histogram (baseline)", "clip": "CLIP ViT-B/32", "fashionclip": "FashionCLIP"}
MODELS = ["color_hist", "clip", "fashionclip"]


def pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def retrieval_chart(summ: pd.DataFrame) -> None:
    style()
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    ks = ["R@1", "R@5", "R@10", "R@20"]
    for ax, mode, title in zip(axes, ["none", "group"], ["Search whole gallery", "Filter to detected category group"]):
        d = summ[summ["filter"] == mode].set_index("model").reindex(MODELS)
        x = np.arange(len(ks))
        w = 0.26
        for i, m in enumerate(MODELS):
            vals = d.loc[m, ks].to_numpy(float)
            color = NEUTRAL if m == "color_hist" else SERIES[i - 1]
            ax.bar(x + (i - 1) * w, vals * 100, width=w, color=color, label=MODEL_LABEL[m], edgecolor="#fcfcfb", linewidth=2)
            ax.text(x[-1] + (i - 1) * w, vals[-1] * 100 + 0.6, f"{vals[-1] * 100:.1f}", ha="center", fontsize=8)
        ax.set_xticks(x, ks)
        ax.grid(axis="x", visible=False)
        ax.set_title(title)
    axes[0].set_ylabel("consumer-to-shop recall (%)")
    axes[1].legend(loc="upper left")
    fig.suptitle("DeepFashion2 consumer-to-shop retrieval: 12,377 queries vs 36,961 shop items", x=0.01, ha="left",
                 fontweight="bold", fontsize=12)
    fig.tight_layout()
    fig.savefig(RESULTS / "retrieval" / "retrieval_recall.png")
    plt.close(fig)


def per_group_recall(models: list[str]) -> pd.DataFrame:
    rows = []
    for m in models:
        r = pd.read_csv(RESULTS / "retrieval" / f"df2_c2s_ranks_{m}.csv")
        for g, d in r.groupby("group"):
            rows.append({"model": m, "group": g, "n_queries": len(d), **recall_at_k(d.rank_group, ks=(1, 5, 10))})
    return pd.DataFrame(rows)


def per_group_chart(pg: pd.DataFrame) -> None:
    style()
    fig, ax = plt.subplots(figsize=(9, 4))
    groups = [g for g in GROUPS if g in set(pg.group)]
    x = np.arange(len(groups))
    w = 0.26
    for i, m in enumerate(MODELS):
        d = pg[pg.model == m].set_index("group").reindex(groups)
        color = NEUTRAL if m == "color_hist" else SERIES[i - 1]
        ax.bar(x + (i - 1) * w, d["R@10"] * 100, width=w, color=color, label=MODEL_LABEL[m], edgecolor="#fcfcfb", linewidth=2)
    n = pg[pg.model == MODELS[0]].set_index("group").reindex(groups).n_queries
    ax.set_xticks(x, [f"{g}\n(n={c:,})" for g, c in zip(groups, n)])
    ax.grid(axis="x", visible=False)
    ax.set_ylabel("Recall@10 (%), category-filtered")
    ax.set_title("Consumer-to-shop Recall@10 by garment group")
    ax.legend(loc="upper left")
    fig.tight_layout()
    fig.savefig(RESULTS / "retrieval" / "recall10_by_group.png")
    plt.close(fig)


def main() -> None:
    lines = ["# Results (auto-generated by `python -m src.eval.report`)", "",
             "Every number below is read from a file in `results/`. Nothing is typed by hand.", ""]

    # Detection
    det = json.loads((RESULTS / "detection" / "det_test_metrics.json").read_text())
    trs = json.loads((RESULTS / "detection" / "train_sample_metrics.json").read_text())
    pc = pd.read_csv(RESULTS / "detection" / "det_test_per_class.csv")
    lines += ["## Detection: pretrained DeepFashion2 YOLOv8s-seg (third-party weights, evaluated by us)", "",
              "| split | images | boxes | box mAP@50 | box mAP@50-95 | precision | recall | mask mAP@50 | mask mAP@50-95 |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    off = json.loads((RESULTS / "detection" / "det_test_official_boxes_metrics.json").read_text())
    lines.append(f"| **det_test vs official DF2 boxes** (headline) | {det['images']:,} | {det['instances']:,} | "
                 f"**{off['mAP50']:.3f}** | **{off['mAP50_95']:.3f}** | {off['precision']:.3f} | {off['recall']:.3f} | n/a | n/a |")
    for name, d in [("det_test vs polygon-extent boxes", det), ("DF2-train sample vs polygon-extent boxes (leakage check)", trs)]:
        lines.append(f"| {name} | {d['images']:,} | {d['instances']:,} | {d['mAP50']:.3f} | {d['mAP50_95']:.3f} | "
                     f"{d['precision']:.3f} | {d['recall']:.3f} | {d['mask_mAP50']:.3f} | {d['mask_mAP50_95']:.3f} |")
    lines += ["", "Official DF2 boxes and the boxes Ultralytics derives from polygons differ (median IoU 0.943 on det_test), "
              "which mainly moves mAP@50-95. Per-class rows below use polygon-extent boxes."]
    lines += ["", "Per class on det_test:", "", "| class | test boxes | precision | recall | mAP@50 | mAP@50-95 |",
              "|---|---:|---:|---:|---:|---:|"]
    for r in pc.sort_values("mAP50", ascending=False).itertuples():
        lines.append(f"| {r.category} | {r.test_instances:,} | {r.precision:.3f} | {r.recall:.3f} | {r.mAP50:.3f} | {r.mAP50_95:.3f} |")

    # Retrieval
    summ = pd.read_csv(RESULTS / "retrieval" / "df2_c2s_summary.csv")
    models = [m for m in MODELS if m in set(summ.model)]
    retrieval_chart(summ)
    lines += ["", "## Retrieval: DeepFashion2 consumer-to-shop (GT crops, 12,377 queries vs 36,961 shop items)", "",
              "| embedding | category filter | R@1 | R@5 | R@10 | R@20 |", "|---|---|---:|---:|---:|---:|"]
    for r in summ.set_index(["model", "filter"]).reindex([(m, f) for m in models for f in ("none", "group")]).reset_index().itertuples():
        lines.append(f"| {MODEL_LABEL[r.model]} | {'group' if r.filter == 'group' else 'none'} | {pct(r._5, 2)} | "
                     f"{pct(r._6, 2)} | {pct(r._7, 2)} | {pct(r._8, 2)} |")
    pg = per_group_recall(models)
    pg.to_csv(RESULTS / "retrieval" / "df2_c2s_by_group.csv", index=False)
    per_group_chart(pg)
    lines += ["", "Recall@10 by garment group (category-filtered):", "",
              "| group | queries | " + " | ".join(MODEL_LABEL[m] for m in models) + " |",
              "|---|---:|" + "---:|" * len(models)]
    for g in [g for g in GROUPS if g in set(pg.group)]:
        d = pg[pg.group == g].set_index("model")
        lines.append(f"| {g} | {int(d.n_queries.iloc[0]):,} | " + " | ".join(pct(d.loc[m, 'R@10']) for m in models) + " |")

    wc = pd.read_csv(RESULTS / "retrieval" / "catalog_wrong_category_unfiltered.csv")
    loo = pd.read_csv(RESULTS / "retrieval" / "catalog_leave_one_out.csv")
    lines += ["", "## Retrieval against the product catalog (17,330 products)", "",
              "| embedding | wrong-category share of top-5 **without** filter | same articleType @5 (LOO) | same colour @5 (LOO) |",
              "|---|---:|---:|---:|"]
    for m in models:
        a, b = wc.set_index("model").loc[m], loo.set_index("model").loc[m]
        lines.append(f"| {MODEL_LABEL[m]} | {pct(a['wrong_cat@5'])} | {pct(b['same_articleType@5'])} | {pct(b['same_colour@5'])} |")

    # Latency
    lat_files = sorted((RESULTS / "latency").glob("latency_*.json"))
    if lat_files:
        lines += ["", "## Latency (end-to-end per photo, after warm-up)", "",
                  "| embedding | photos | device | median | p95 | detect median | embed median | search median |",
                  "|---|---:|---|---:|---:|---:|---:|---:|"]
        for f in lat_files:
            L = json.loads(f.read_text())
            lines.append(f"| {MODEL_LABEL[L['model']]} | {L['n_images']} | {L['env']['machine']} / {L['env']['device']} | "
                         f"{L['total_ms']['median']:.0f} ms | {L['total_ms']['p95']:.0f} ms | {L['detect_ms']['median']:.0f} ms | "
                         f"{L['embed_ms']['median']:.0f} ms | {L['search_ms']['median']:.2f} ms |")

    (RESULTS / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
